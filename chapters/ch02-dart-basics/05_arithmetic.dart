// Глава 2, «Арифметика» и «Комментарии».
void main() {
  print(7 + 2);    // 9
  print(7 - 2);    // 5
  print(7 * 2);    // 14
  print(7 / 2);    // 3.5
  print(7 ~/ 2);   // 3   — деление нацело, остаток отбрасывается
  print(7 % 2);    // 1   — остаток от деления

  print(10 / 5);   // 2.0 — обычное деление всегда даёт дробное число

  print(2 + 3 * 4);     // 14
  print((2 + 3) * 4);   // 20

  var score = 100;
  var lives = 3;
  var level = 1;

  score += 10;   // то же самое, что score = score + 10
  score -= 5;
  lives--;       // на единицу меньше
  level++;       // на единицу больше
  print('Счёт $score, жизней $lives, уровень $level');

  // Это комментарий. Он для человека, а не для компьютера.
  var speed = 12;   // скорость в клетках за секунду
  print(speed);

  /*
    Так можно закомментировать
    сразу несколько строк.
  */
}
