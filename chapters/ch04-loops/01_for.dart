// Глава 4, «Зачем повторять» и «Цикл for: считаем по порядку».
void main() {
  // Без цикла — копировать строки:
  print('С днём рождения!');
  print('С днём рождения!');
  print('С днём рождения!');
  // ...и ещё семь раз

  // С циклом — те самые сто приветствий:
  for (var i = 1; i <= 100; i++) {
    print('С днём рождения! (номер $i)');
  }
}
