// Глава 5, «Полезные свойства».
void main() {
  var scores = [98, 85, 77, 100];

  print(scores.length);      // 4     — сколько элементов
  print(scores.isEmpty);     // false — пуст ли
  print(scores.isNotEmpty);  // true
  print(scores.first);       // 98    — первый
  print(scores.last);        // 100   — последний
}
